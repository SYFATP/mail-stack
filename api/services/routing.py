"""Safe domain policy, deterministic PCRE maps and atomic runtime generations."""
from __future__ import annotations
import hashlib
import json
import os
from pathlib import Path
import re
import threading
import sqlite3
import time
import uuid

ROUTING_VERSION = 4
_LOCK = threading.RLock()
LABEL = r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?"
LOCAL = r"[a-z0-9](?:[a-z0-9._+-]{0,62}[a-z0-9_+-])?"
DOMAIN_FIELDS = (
    "domain", "enabled", "users", "dkim_selector", "spf", "dmarc", "mx",
    "receive_mode", "receive_enabled", "send_enabled", "receive_subdomains",
    "max_subdomain_depth", "source_type", "source_status", "dns_provider",
)


def normalize_domain(value: str) -> str:
    value = str(value or "").strip().rstrip(".").lower()
    try:
        value = value.encode("idna").decode("ascii")
    except UnicodeError as exc:
        raise ValueError("invalid domain") from exc
    labels = value.split(".")
    if (len(value) > 253 or len(labels) < 2 or len(labels[-1]) < 2
            or labels[-1].isdigit() or any(not re.fullmatch(LABEL, x) for x in labels)):
        raise ValueError("invalid domain")
    return value


def normalize_local(value: str) -> str:
    value = str(value or "").strip().lower()
    if not re.fullmatch(LOCAL, value) or ".." in value:
        raise ValueError("invalid local-part")
    return value


def normalize_address(value: str) -> str:
    value = str(value or "").strip()
    if value.count("@") != 1:
        raise ValueError("invalid address")
    local, domain = value.split("@")
    result = normalize_local(local) + "@" + normalize_domain(domain)
    if len(result.encode("ascii")) > 254:
        raise ValueError("address too long")
    return result


def canonical_row(row: dict) -> dict:
    row = dict(row)
    users = row.get("users", [])
    if isinstance(users, str):
        users = json.loads(users)
    out = {name: row.get(name) for name in DOMAIN_FIELDS}
    out.update(domain=normalize_domain(row["domain"]), users=sorted(set(normalize_local(x) for x in users)),
               enabled=bool(row.get("enabled", 1)), receive_enabled=bool(row.get("receive_enabled", 1)),
               send_enabled=bool(row.get("send_enabled", 1)), receive_subdomains=bool(row.get("receive_subdomains", 0)),
               receive_mode=row.get("receive_mode", "fixed"), max_subdomain_depth=int(row.get("max_subdomain_depth", 3)),
               dkim_selector=row.get("dkim_selector") or "default", source_type=row.get("source_type") or "manual",
               source_status=row.get("source_status") or "imported", dns_provider=row.get("dns_provider") or "cloudflare")
    if out["receive_mode"] not in {"fixed", "catch_all"} or not 0 <= out["max_subdomain_depth"] <= 7:
        raise ValueError("invalid receive policy")
    if not re.fullmatch(r"[a-z0-9][a-z0-9._-]{0,62}", out["dkim_selector"]):
        raise ValueError("invalid DKIM selector")
    return out


def config_hash(row: dict) -> str:
    return hashlib.sha256(json.dumps(canonical_row(row), sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def _domain_pattern(row: dict, rows: list[dict]) -> str:
    base = row["domain"]
    depth = row["max_subdomain_depth"] if row["receive_subdomains"] else 0
    children = [r["domain"] for r in rows if r["domain"].endswith("." + base)]
    exclusions = "".join(r"(?!(?:" + LABEL + r"\.)*" + re.escape(child) + r"\z)" for child in children)
    return exclusions + "(?:" + LABEL + r"\.){0," + str(depth) + "}" + re.escape(base)


def compile_maps(rows: list[dict]) -> dict[str, str]:
    rows = sorted((canonical_row(x) for x in rows), key=lambda x: (-len(x["domain"].split(".")), x["domain"]))
    domains = ["# Generated by mail-stack; edit domain policy through the API."]
    mailboxes = ["# Diagnostic recipient acceptance table only; mailbox paths use generation-bound SQLite."]
    for row in rows:
        if not row["enabled"] or not row["receive_enabled"] or row["source_status"] in {"released", "revoked", "expired"}:
            continue
        pattern = _domain_pattern(row, rows)
        domains.append(r"/\A(?=.{1,253}\z)" + pattern + r"\z/ OK")
        if row["receive_mode"] == "catch_all":
            local = LOCAL
        elif row["users"]:
            local = "(?:" + "|".join(re.escape(x) for x in row["users"]) + ")"
        else:
            continue
        mailboxes.append(r"/\A(?=.{1,254}\z)(?![^@]*\.\.)(" + local + ")@(" + pattern + r")\z/ OK")
    # Even an empty configuration must be a valid, fail-closed PCRE table.
    domains.append(r"/\A(?!)\z/ OK")
    mailboxes.append(r"/\A(?!)\z/ OK")
    return {"vdomains.pcre": "\n".join(domains) + "\n", "vmailbox.pcre": "\n".join(mailboxes) + "\n"}


def recipient_policy(address: str, rows: list[dict]) -> dict:
    try:
        address = normalize_address(address)
    except ValueError:
        return {"ok": False, "reason": "invalid_recipient"}
    local, domain = address.split("@")
    rows = [canonical_row(x) for x in rows]
    candidates = [x for x in rows if domain == x["domain"] or domain.endswith("." + x["domain"])]
    if not candidates:
        return {"ok": False, "reason": "unmanaged_domain"}
    row = max(candidates, key=lambda x: len(x["domain"]))
    context = {"managed_domain": row["domain"], "recipient_domain": domain}
    depth = len(domain.split(".")) - len(row["domain"].split("."))
    if not row["enabled"] or not row["receive_enabled"] or row["source_status"] in {"released", "revoked", "expired"}:
        return {"ok": False, "reason": "domain_disabled", **context}
    if depth and (not row["receive_subdomains"] or depth > row["max_subdomain_depth"]):
        return {"ok": False, "reason": "subdomain_not_allowed", **context}
    if row["receive_mode"] == "fixed" and local not in row["users"]:
        return {"ok": False, "reason": "unlisted_recipient", **context}
    return {"ok": True, "reason": row["receive_mode"], "managed_domain": row["domain"],
            "recipient_domain": domain, "address": address, "maildir": f"{domain}/{local}/Maildir/"}


def _atomic_text(path: Path, value: str):
    temporary = path.with_name("." + path.name + "." + uuid.uuid4().hex + ".tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(value)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


# Native, local SQLite maps are permitted by virtual(8), unlike regexp
# substitutions or socketmaps. This read-only snapshot never contains mailbox
# reservations and never opens the mutable application database.
MAILBOX_QUERY = """
WITH RECURSIVE
input(address) AS (SELECT lower('__ADDRESS__')),
parts AS (
 SELECT address, substr(address,1,instr(address,'@')-1) AS local,
        substr(address,instr(address,'@')+1) AS actual
 FROM input WHERE length(address) BETWEEN 3 AND 254 AND instr(address,'@') > 1
),
labels(label,tail) AS (
 SELECT NULL, actual || '.' FROM parts
 UNION ALL
 SELECT substr(tail,1,instr(tail,'.')-1),substr(tail,instr(tail,'.')+1)
 FROM labels WHERE tail != ''
),
policy AS (
 SELECT d.*,p.local,p.actual,p.address,
   length(p.actual)-length(replace(p.actual,'.',''))
     -length(d.domain)+length(replace(d.domain,'.','')) AS depth
 FROM domains d JOIN parts p ON p.actual=d.domain
   OR substr(p.actual,-length(d.domain)-1)='.'||d.domain
 ORDER BY length(d.domain) DESC LIMIT 1
)
SELECT actual||'/'||local||'/Maildir/' FROM policy
WHERE enabled=1 AND receive_enabled=1
 AND source_status NOT IN ('released','revoked','expired')
 AND (depth=0 OR (receive_subdomains=1 AND depth<=max_subdomain_depth))
 AND (receive_mode='catch_all' OR EXISTS(SELECT 1 FROM users u WHERE u.domain=policy.domain AND u.local=policy.local))
 AND length(local) BETWEEN 1 AND 64 AND instr(local,'..')=0
 AND local NOT GLOB '*[^a-z0-9._+-]*'
 AND substr(local,1,1) GLOB '[a-z0-9]' AND substr(local,-1) GLOB '[a-z0-9_+-]'
 AND length(actual) BETWEEN 3 AND 253 AND actual NOT GLOB '*[^a-z0-9.-]*'
 AND NOT EXISTS(SELECT 1 FROM labels WHERE label IS NOT NULL AND
    (length(label) NOT BETWEEN 1 AND 63 OR substr(label,1,1) NOT GLOB '[a-z0-9]' OR substr(label,-1) NOT GLOB '[a-z0-9]'))
"""


def mailbox_query(address: str) -> str:
    """Test helper using the same SQL quoting that Postfix's SQLite map applies."""
    return MAILBOX_QUERY.replace('__ADDRESS__', address.replace("'", "''"))


def _publish_sqlite(rows: list[dict], directory: Path):
    destination = directory / 'recipients.sqlite'
    if destination.exists():
        c = sqlite3.connect(destination)
        try:
            fields = ('domain','enabled','receive_enabled','source_status','receive_subdomains','max_subdomain_depth','receive_mode')
            expected = sorted(tuple(row[name] for name in fields) for row in rows)
            actual = c.execute('SELECT ' + ','.join(fields) + ' FROM domains ORDER BY domain').fetchall()
            expected_users = sorted((row['domain'], local) for row in rows for local in row['users'])
            actual_users = c.execute('SELECT domain,local FROM users ORDER BY domain,local').fetchall()
            if expected != actual or expected_users != actual_users:
                raise ValueError('routing SQLite generation content mismatch')
        finally:
            c.close()
        return
    temporary = directory / ('.recipients.' + uuid.uuid4().hex + '.tmp')
    try:
        c = sqlite3.connect(temporary)
        try:
            c.execute('CREATE TABLE domains(domain TEXT PRIMARY KEY, enabled INTEGER, receive_enabled INTEGER, source_status TEXT, receive_subdomains INTEGER, max_subdomain_depth INTEGER, receive_mode TEXT)')
            c.execute('CREATE TABLE users(domain TEXT, local TEXT, PRIMARY KEY(domain,local))')
            for row in rows:
                c.execute('INSERT INTO domains VALUES(?,?,?,?,?,?,?)', [row[name] for name in ('domain','enabled','receive_enabled','source_status','receive_subdomains','max_subdomain_depth','receive_mode')])
                c.executemany('INSERT INTO users VALUES(?,?)', [(row['domain'],local) for local in row['users']])
            c.commit()
        finally:
            c.close()
        with temporary.open('r+b') as stream:
            os.fsync(stream.fileno())
        os.replace(temporary, destination)
    finally:
        temporary.unlink(missing_ok=True)


def publish(rows: list[dict], runtime_dir: Path) -> str:
    """Write an immutable generation, then swap one pointer. No fake applied ACK."""
    with _LOCK:
        rows = sorted((canonical_row(x) for x in rows), key=lambda x: x["domain"])
        generation = hashlib.sha256(json.dumps({"routing_version": ROUTING_VERSION, "domains": rows}, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
        directory = runtime_dir / "generations" / generation
        directory.mkdir(parents=True, exist_ok=True)
        enabled = [x for x in rows if x["enabled"] and x["source_status"] not in {"released", "revoked", "expired"}]
        key_domains = [x for x in rows if x["source_status"] not in {"released", "revoked", "expired"}]
        files = compile_maps(rows)
        files.update({
            "key-domains.list": "".join(x["domain"] + "\n" for x in key_domains),
            "key-selectors.list": "".join(f"{x['domain']} {x['dkim_selector']}\n" for x in key_domains),
            "domains.list": "".join(x["domain"] + "\n" for x in enabled),
            "mailboxes.list": "".join(f"{u}@{x['domain']}\n" for x in enabled for u in x["users"]),
            "selectors.list": "".join(f"{x['domain']} {x['dkim_selector']}\n" for x in enabled),
            "manifest.json": json.dumps({"generation": generation, "routing_version": ROUTING_VERSION, "domains": rows}, sort_keys=True, indent=2) + "\n",
        })
        for name, value in files.items():
            # Content-addressed generations are immutable across API restarts.
            path = directory / name
            if not path.exists():
                _atomic_text(path, value)
            elif path.read_text(encoding="utf-8") != value:
                raise ValueError("routing generation content mismatch")
        _publish_sqlite(rows, directory)
        # %% escapes a literal percent in Postfix query templates; %s is the
        # SQL-quoted input key, not Python/string interpolation of a recipient.
        query = ' '.join(MAILBOX_QUERY.split()).replace('%','%%').replace('__ADDRESS__','%s')
        map_config = 'dbpath = /etc/postfix/mail-stack/' + generation + '/recipients.sqlite\nquery = ' + query + '\n'
        map_path = directory / 'vmailbox.cf'
        if not map_path.exists():
            _atomic_text(map_path, map_config)
        elif map_path.read_text(encoding='utf-8') != map_config:
            raise ValueError('routing SQLite query generation content mismatch')
        _atomic_text(runtime_dir / "routing.current", generation + "\n")
        # Compatibility files only; upgraded consumers use the immutable snapshot.
        for name in ("domains.list", "mailboxes.list", "selectors.list"):
            _atomic_text(runtime_dir / name, files[name])
        return generation


def _generation_domains(runtime_dir: Path, generation: str) -> list[dict]:
    manifest = json.loads((runtime_dir / "generations" / generation / "manifest.json").read_text())
    rows = manifest["domains"]
    digest = hashlib.sha256(json.dumps(
        {"routing_version": manifest["routing_version"], "domains": rows},
        sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    if (manifest["generation"] != generation or digest != generation
            or manifest["routing_version"] != ROUTING_VERSION
            or not isinstance(rows, list)):
        raise ValueError("invalid routing manifest")
    return rows


class AppliedStateSnapshot:
    """Request-local routing evidence; immutable manifests are read once each."""
    def __init__(self, runtime_dir: Path):
        self.runtime_dir = runtime_dir
        self.generation = None
        self.ack = {}
        self.manifests = {}
        try:
            self.generation = (runtime_dir / "routing.current").read_text().strip()
            self.ack = json.loads((runtime_dir / "postfix-applied.json").read_text())
        except (OSError, ValueError, TypeError):
            pass

    def _domains(self, generation):
        if generation not in self.manifests:
            try:
                self.manifests[generation] = _generation_domains(self.runtime_dir, generation)
            except (OSError, ValueError, TypeError, AttributeError, KeyError):
                self.manifests[generation] = None
        rows = self.manifests[generation]
        if rows is None:
            raise ValueError("invalid routing manifest")
        return rows

    def for_row(self, row=None):
        generation, ack = self.generation, self.ack
        try:
            if (generation and re.fullmatch(r"[a-f0-9]{64}", generation)
                    and 0 <= time.time() - float(ack.get("applied_at", 0)) <= 15):
                if ack.get("generation") == generation:
                    return {"generation": generation, **ack}
                applied = ack.get("generation")
                if row is not None and ack.get("status") == "applied" and re.fullmatch(r"[a-f0-9]{64}", applied):
                    policy = canonical_row(row)
                    domain = policy["domain"]

                    def relevant(rows):
                        return {r["domain"]: r for r in rows
                                if r["domain"] == domain or r["domain"].endswith("." + domain)}

                    desired = relevant(self._domains(generation))
                    previous = relevant(self._domains(applied))
                    if desired.get(domain) == policy and previous == desired:
                        return {**ack, "desired_generation": generation}
        except (OSError, ValueError, TypeError, AttributeError, KeyError):
            pass
        return {"status": "pending", "generation": generation}


def applied_state(runtime_dir: Path, *, row: dict | None = None) -> dict:
    """Keep fresh applied evidence only for unchanged domain/descendant policies."""
    return AppliedStateSnapshot(runtime_dir).for_row(row)
